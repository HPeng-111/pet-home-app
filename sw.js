// ============================================================
// sw.js — Service Worker（浏览器离线服务）
// ============================================================
// 作用：
// 1. 让浏览器识别这个网站是 PWA（可安装到桌面）
// 2. 缓存资源，离线也能打开（当前使用简单策略，有网就从服务器取）
//
// 比喻：快递驿站的管家
//   - 你有网时：直接从快递公司（服务器）拿
//   - 你离线时：从驿站（缓存）拿之前存好的
//
// 生命周期：
//   install → activate → fetch
//   安装     激活       拦截请求

// --- install 事件：SW 安装时触发 ---
// self = Service Worker 全局对象（相当于浏览器里的 window）
self.addEventListener('install', () => {
  // skipWaiting()：跳过等待，立即激活
  // 不用等旧版本 SW 关闭，新的直接接管
  self.skipWaiting()
})

// --- fetch 事件：每次网页发请求时触发 ---
// 拦截所有网络请求（HTML/CSS/JS/图片/MQTT...）
self.addEventListener('fetch', (e) => {
  // 当前策略：简单转发，不缓存
  // e.request = 原始的请求对象
  // fetch(e.request) = 直接向服务器发同样的请求
  // e.respondWith(...) = 用这个结果作为响应
  //
  // 进阶玩法（答辩可讲）：
  //   可以改成"缓存优先"策略：
  //     先查缓存，有就用缓存的（秒开）
  //     没缓存再联网，存到缓存里（下次秒开）
  e.respondWith(fetch(e.request))
})
